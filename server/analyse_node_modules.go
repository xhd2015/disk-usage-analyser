package server

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"disk-usage-analyser/tmpfiles"
)

// AnalyseNodeModulesOptions configures single-path node_modules analysis.
type AnalyseNodeModulesOptions struct {
	// SkipShared skips analyse.Analyse (pnpm/bun shared metrics). Faster for PM/pkgjson/git checks.
	SkipShared bool
	// Verbose emits per-step timing logs to stderr.
	Verbose bool
}

// AnalyseNodeModules computes the same NamedHit fields shown in the node_modules table UI.
func AnalyseNodeModules(inputPath, homeDir string, opts AnalyseNodeModulesOptions) (NamedHit, error) {
	log := opts.verboseLog
	totalStart := time.Now()
	defer func() {
		log("total duration=%s", time.Since(totalStart))
	}()

	absPath := filepath.Clean(resolveTildePath(inputPath, homeDir))
	log("inputPath=%s absPath=%s homeDir=%s", inputPath, absPath, homeDir)

	t0 := time.Now()
	info, err := os.Stat(absPath)
	if err != nil {
		log("stat duration=%s err=%v", time.Since(t0), err)
		return NamedHit{}, err
	}
	log("stat duration=%s isDir=%v", time.Since(t0), info.IsDir())
	if !info.IsDir() {
		return NamedHit{}, fmt.Errorf("%s is not a directory", absPath)
	}

	displayPath := inputPath
	if !strings.HasPrefix(inputPath, "~/") {
		displayPath = tmpfiles.DisplayPath(absPath, homeDir)
	} else {
		displayPath = filepath.ToSlash(inputPath)
	}
	log("displayPath=%s", displayPath)

	names := map[string]bool{"node_modules": true}
	t0 = time.Now()
	size, err := tmpfiles.DirSize(absPath, names)
	if err != nil {
		log("dir_size duration=%s err=%v", time.Since(t0), err)
		return NamedHit{}, err
	}
	log("dir_size duration=%s size=%s (%d B)", time.Since(t0), tmpfiles.FormatHumanSize(size), size)

	hit := NamedHit{
		Path:      displayPath,
		Name:      "node_modules",
		Size:      size,
		SizeHuman: tmpfiles.FormatHumanSize(size),
	}

	t0 = time.Now()
	applyPackageManager(&hit, absPath, "node_modules")
	log("detect_package_manager duration=%s pm=%s", time.Since(t0), hit.PackageManager)

	t0 = time.Now()
	applyHasPackageJSON(&hit, absPath, "node_modules")
	log("detect_has_package_json duration=%s hasPackageJson=%v", time.Since(t0), hit.HasPackageJSON)

	t0 = time.Now()
	applyGitTracked(&hit, absPath, "node_modules")
	log("detect_git_tracked duration=%s gitTracked=%v", time.Since(t0), hit.GitTracked)

	if opts.SkipShared {
		zeroSharedFields(&hit)
		log("shared_metrics skipped (-quick)")
	} else {
		applySharedMetricsLogged(&hit, absPath, log)
	}

	return hit, nil
}

func (opts AnalyseNodeModulesOptions) verboseLog(format string, args ...any) {
	if !opts.Verbose {
		return
	}
	fmt.Fprintf(os.Stderr, "[analyse-node-modules] "+format+"\n", args...)
}